// Task lives in types.ts, which a concurrent change owns — the optional field
// is added by augmentation instead (recents.ts precedent). Fold into types.ts
// when convenient.
declare module '../types' {
  interface Task {
    /** User-added frontmatter keys (aliases, cssclasses, …) captured at hydrate and re-emitted after the owned keys on save. Absent when the file has none. */
    extraFrontmatter?: Record<string, unknown>
  }
}

const IOC_TYPES = new Set(['ip', 'domain', 'hash', 'url', 'email'])
const LINK_TYPES = new Set(['blocks', 'relates-to', 'duplicates'])
const BUCKET_IDS = new Set(BUCKETS.map((b) => b.id))

function hydrateBucket(raw: unknown): IssueBucket {
  return typeof raw === 'string' && BUCKET_IDS.has(raw as IssueBucket) ? (raw as IssueBucket) : 'none'
}

function hydrateIocs(raw: unknown): Ioc[] {
  if (!Array.isArray(raw)) return []
  const iocs: Ioc[] = []
  for (const entry of raw) {
    if (!entry || typeof entry !== 'object') continue
    const i = entry as Record<string, unknown>
    if (typeof i.value !== 'string' || !i.value || typeof i.type !== 'string' || !IOC_TYPES.has(i.type)) continue
    // note is omitted (never undefined) when absent — the YAML emitter writes literal `undefined` otherwise
    iocs.push({
      type: i.type as Ioc['type'],
      value: i.value,
      ...(typeof i.note === 'string' && i.note ? { note: i.note } : {})
    })
  }
  return iocs
}

/** Accept only well-formed entries ({type in the union, taskId string}); drop garbage silently (hydrateIocs precedent). */
function hydrateLinks(raw: unknown): TaskLink[] {
  if (!Array.isArray(raw)) return []
  const links: TaskLink[] = []
  for (const entry of raw) {
    if (!entry || typeof entry !== 'object') continue
    const l = entry as Record<string, unknown>
    if (typeof l.type !== 'string' || !LINK_TYPES.has(l.type)) continue
    if (typeof l.taskId !== 'string' || !l.taskId) continue
    links.push({ type: l.type as TaskLink['type'], taskId: l.taskId })
  }
  return links
}

function hydrateActivity(raw: unknown): ActivityEntry[] {
  if (!Array.isArray(raw)) return []
  const entries: ActivityEntry[] = []
  for (const entry of raw) {
    if (!entry || typeof entry !== 'object') continue
    const a = entry as Record<string, unknown>
    if (typeof a.at !== 'string' || typeof a.field !== 'string') continue
    entries.push({
      at: a.at,
      field: a.field,
      from: typeof a.from === 'string' ? a.from : '',
      to: typeof a.to === 'string' ? a.to : ''
    })
  }
  return entries
}

