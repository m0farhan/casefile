/**
 * 'fm' — only frontmatter changed; body content is unaffected. Save path can
 * use processFrontMatter and skip reading the body.
 * 'full' — body content depends on the change (description edited, file
 * renamed, archived flag flipped, structural relationships moved). Save path
 * rewrites the whole file atomically via vault.process.
 */
type DirtyKind = 'fm' | 'full'

/** Patches that touch any of these require rewriting the body, not just the frontmatter. */
function patchNeedsBodyRewrite(patch: Partial<Task>): boolean {
  // `subtasks` changes the parent's `## Subtasks` list; `comments` the
  // `## Comments` section — both live in the body.
  return (
    patch.description !== undefined ||
    patch.archived !== undefined ||
    patch.subtasks !== undefined ||
    patch.comments !== undefined
  )
}

/** Recover description AND comments from a raw on-disk body (unhydrated tasks). */
function recoverBodyInto(task: Task, rawBody: string): void {
  const { rest, comments } = splitCommentsSection(rawBody)
  task.description = stripAutoGeneratedContent(rest)
  task.comments = comments
}

/** A Project's keys that are not the board's own fields: its cases, and what the store derives from where its note sits. */
const NOT_BOARD_FIELDS = new Set(['tasks', 'taskIndex', 'filePath', 'detached'])

/** Each board field as JSON, the form the three-way board merge compares. */
function boardFields(project: Project): Map<string, string | undefined> {
  const fields = new Map<string, string | undefined>()
  for (const [key, value] of Object.entries(project)) {
    if (!NOT_BOARD_FIELDS.has(key)) fields.set(key, JSON.stringify(value))
  }
  return fields
}

/** A basename of this exact length that prefixes the title's slug is kept as-is. */
const LEGACY_SLUG_CAP = 40

/**
 * Pick a save path. New tasks get the exact-title filename; an existing file is
 * left where it is when its name still matches the title in ANY historical
 * naming scheme (exact title, pre-2.3 lowercase-dash slug, id-suffixed or
 * 40-capped slug variants) — so adopting exact names never mass-renames a
 * vault; files pick up the new form only when their title actually changes.
 */
function resolveTaskPath(task: Task, folder: string, previousPath: string | undefined): string {
  const desired = taskFilePath(task.title, folder)
  if (!previousPath) return desired
  const desiredBasename = desired.slice(desired.lastIndexOf('/') + 1).replace(/\.md$/, '')
  const previousFolder = previousPath.slice(0, previousPath.lastIndexOf('/'))
  const previousBasename = previousPath.slice(previousPath.lastIndexOf('/') + 1).replace(/\.md$/, '')
  if (previousFolder !== folder) return desired
  if (previousBasename === desiredBasename) return previousPath
  // A name written before "Archive" and "attachments" were reserved moves to
  // the safe name on its next save instead of being kept.
  if (isReservedTaskName(previousBasename)) return desired
  const oldSlug = taskSlugLegacy(task.title)
  if (previousBasename === oldSlug) return previousPath
  if (previousBasename === `${oldSlug}-${task.id.slice(0, 8)}`) return previousPath
  if (previousBasename.length === LEGACY_SLUG_CAP && previousBasename === oldSlug.slice(0, LEGACY_SLUG_CAP)) {
    return previousPath
  }
  return desired
}

/**
 * A key embedded at the start of a title ("SOC-4: Fix things"). The number
 * must end the token (the lookahead), so "CVE-2024-3400 exploited" is never
 * read as key CVE-2024 with "-3400 exploited" left as the title.
 */
const EMBEDDED_KEY = /^([A-Z][A-Z0-9]+)-(\d+)(?=[:\s]|$):?\s*/

/**
 * The prefix most titles on a board already carry as an embedded key, or ''
 * when none does. Exported so the adopt command can show it to the analyst to
 * confirm before any key is written: keys are immutable.
 */
export function inferIssueKeyPrefix(tasks: Task[]): string {
  const counts = new Map<string, number>()
  for (const { task } of flattenTasks(tasks)) {
    const m = EMBEDDED_KEY.exec(task.title)
    if (m) counts.set(m[1], (counts.get(m[1]) ?? 0) + 1)
  }
  return [...counts.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] ?? ''
}

/** Refuse a title that makes no file name at all: '' or '...' would write `Tasks/.md`. */
function assertNameable(title: string): void {
  if (taskFilePath(title, '').endsWith('/.md')) {
    throw new Error('A case title needs at least one character that can go in a file name.')
  }
}

